import type { AssessmentLevel, EimsTestCase, FeatureId } from './test-cases';

type CaseRow = [string, string, AssessmentLevel, string, string];

const featureLabels: Record<FeatureId, string> = {
  search: '検索機能', registration: '登録機能', update: '更新機能', delete: '削除機能',
};

function defineCases(feature: FeatureId, rows: CaseRow[]): EimsTestCase[] {
  return rows.map(([id, title, level, input, expected]) => ({
    id, feature, title, level, input, expected,
    description: `${title}について、実際の画面操作から動作を確認する。`,
    note: `${featureLabels[feature]}の設計仕様に基づく確認項目。`,
    hints: level === 'reference'
      ? ['この項目は通常操作の範囲外、または環境操作を伴う参考確認です。']
      : [`${featureLabels[feature]}のController、HTMLフォーム、画面遷移を順番に確認してください。`, '入力値のname属性と送信先URLが設計通りか確認してください。'],
  }));
}

